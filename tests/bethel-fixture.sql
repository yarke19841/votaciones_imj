create role anon nologin;
create role authenticated nologin;
-- Match hosted Supabase direct default grants, not only PostgreSQL PUBLIC.
alter default privileges in schema public grant execute on functions to anon,authenticated;
create schema auth;
create schema extensions;
create extension pgcrypto with schema extensions;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
grant usage on schema auth to anon,authenticated;
grant execute on function auth.uid() to anon,authenticated;
create table public.territories(id bigint primary key,is_active boolean not null default true,active boolean);
create table public.profiles(user_id uuid primary key references auth.users,role text,is_active boolean not null,territory_id bigint);
create table public.people(id bigint primary key,full_name text);
create table public.groups(id bigint primary key,name text,leader_user_id uuid,territory_id bigint,active boolean);
create table public.memberships(id bigint primary key,group_id bigint,person_id bigint,is_member boolean);
create table public.leader_territories(leader_user_id uuid,territory_id bigint);
create table public.pastor_territories(pastor_user_id uuid,territory_id bigint);
