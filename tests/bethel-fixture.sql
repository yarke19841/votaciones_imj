alter table public.groups enable row level security;
alter table public.memberships enable row level security;
alter table public.profiles enable row level security;
alter table public.territories enable row level security;
alter table public.leader_territories enable row level security;
alter table public.pastor_territories enable row level security;
create schema storage;
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text,owner uuid);
alter table storage.objects enable row level security;
grant usage on schema storage to authenticated;
grant select,insert,update,delete on storage.objects to authenticated;
grant usage on schema storage to anon;
grant select on storage.objects to anon;
create schema bethel_security;
create function bethel_security.caller_is_admin() returns boolean language sql stable security definer as $$select exists(select 1 from public.profiles where user_id=auth.uid() and role='admin' and is_active)$$;
