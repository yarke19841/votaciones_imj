-- QA ONLY: all synthetic records rolled back; does not verify HTTP or concurrency.
begin;
create temp table qa_checks(name text, passed boolean);
do $$
declare adm uuid; lead uuid; eid uuid; c1 uuid; c2 uuid; r uuid; pr uuid; pc uuid;
 p1 bigint; p2 bigint; p3 bigint; pd bigint; v jsonb; v2 jsonb; tok uuid; tie uuid; ex uuid; denied boolean;
begin
 select user_id into adm from public.profiles where role='admin' and is_active limit 1;
 select user_id into lead from public.profiles where role='leader' and is_active limit 1;
 if adm is null or lead is null then raise exception 'QA role fixtures missing'; end if;
 insert into public.people(full_name) values('QA rollback voter A') returning id into p1;
 insert into public.people(full_name) values('QA rollback voter B') returning id into p2;
 insert into public.people(full_name) values('QA rollback disabled') returning id into p3;
 insert into public.people(full_name) values('QA rollback duplicate') returning id into pd;
 perform set_config('request.jwt.claim.sub',adm::text,true);
 eid:=public.voting_admin_save_election(null,2099,'QA rollback contract',1,0,9,-79,150);
 c1:=public.voting_admin_save_candidate(null,eid,'QA A','M',null,false,true);
 c2:=public.voting_admin_save_candidate(null,eid,'QA B','M',null,false,true);
 pc:=public.voting_admin_save_candidate(null,null,'QA Practice','M',null,true,true);
 r:=public.voting_admin_save_round(null,eid,'official',1,'new',1,0,array[c1,c2]);
 pr:=public.voting_admin_save_round(null,eid,'practice',1,'new',1,0,array[pc]);
 perform public.voting_enable_person(eid,p1,'QA-ROLLBACK-001',true);
 perform public.voting_enable_person(eid,pd,'qa rollback 001',true);
 perform public.voting_enable_person(eid,p2,'QA-ROLLBACK-002',true);
 perform public.voting_enable_person(eid,p3,'QA-ROLLBACK-003',false);
 insert into qa_checks values('territorial aliases share one identity',(select count(distinct identity_id)=1 from voting_private.identity_people where person_id in(p1,pd)));
 perform public.voting_admin_start_checkin(r);
 perform set_config('request.jwt.claim.sub','',true);
 v:=public.voting_enter('QA-ROLLBACK-001',9,-79); tok:=(v->>'token')::uuid;
 insert into qa_checks values('automatic attendance waits without candidates',v->>'state'='waiting' and (v->>'attended')::boolean and not(v?'candidates'));
 perform public.voting_enter('QA-ROLLBACK-001',9,-79);
 insert into qa_checks values('attendance idempotent',(select count(*)=1 from voting_private.attendance where round_id=r));
 v:=public.voting_enter('QA-ROLLBACK-003',9,-79);
 insert into qa_checks values('disabled arrival stays disabled',v->>'reason'='not_enabled' and (v->>'attended')::boolean);
 insert into qa_checks values('preopening ballot hidden',public.voting_ballot(tok,9,-79)->>'state'='waiting');
 perform set_config('request.jwt.claim.sub',adm::text,true);
 perform public.voting_admin_open_round(r);
 denied:=false;
 begin perform public.voting_admin_open_round(pr); exception when others then denied:=true; end;
 insert into qa_checks values('second opening rejected',denied);
 perform set_config('request.jwt.claim.sub','',true);
 insert into qa_checks values('ballot rechecks location',public.voting_ballot(tok,10,-79)->>'state'='location_denied');
 insert into qa_checks values('submit rechecks location',public.voting_submit(tok,array[c1],10,-79)->>'state'='location_denied');
 insert into qa_checks values('quota revalidated',public.voting_submit(tok,array[c1,c2],9,-79)->>'state'='invalid_quota');
 perform set_config('request.jwt.claim.sub',lead::text,true);
 denied:=false;
 begin perform public.voting_admin_set_exception(r,p1,now()-interval '1 minute',now()+interval '1 hour','QA'); exception when insufficient_privilege then denied:=true; end;
 insert into qa_checks values('leader cannot grant exception',denied);
 perform set_config('request.jwt.claim.sub',adm::text,true);
 v:=public.voting_admin_set_exception(r,p1,now()-interval '1 minute',now()+interval '1 hour','QA'); ex:=(v->>'exception_id')::uuid;
 perform set_config('request.jwt.claim.sub','',true);
 insert into qa_checks values('admin exception permits outside ballot',public.voting_ballot(tok,10,-79)->>'state'='ready');
 perform set_config('request.jwt.claim.sub',adm::text,true);
 perform public.voting_admin_revoke_exception(ex);
 perform set_config('request.jwt.claim.sub','',true);
 insert into qa_checks values('revoked exception denies submit',public.voting_submit(tok,array[c1],10,-79)->>'state'='location_denied');
 insert into qa_checks values('valid ballot accepted',public.voting_submit(tok,array[c1],9,-79)->>'state'='accepted');
 insert into qa_checks values('repeat vote rejected',public.voting_submit(tok,array[c1],9,-79)->>'state'<>'accepted');
 v2:=public.voting_enter('QA-ROLLBACK-002',9,-79);
 insert into qa_checks values('second voter accepted',public.voting_submit((v2->>'token')::uuid,array[c2],9,-79)->>'state'='accepted');
 perform set_config('request.jwt.claim.sub',adm::text,true);
 insert into qa_checks values('pending removes participants',(select count(*)=0 from public.voting_staff_pending(r)));
 v:=public.voting_admin_close_active();
 insert into qa_checks values('close selects active round',v->>'round_id'=r::text);
 insert into qa_checks values('results calculated',(select count(*)=2 and min(vote_count)=1 and max(vote_count)=1 from public.voting_admin_results(r)));
 v:=public.voting_admin_create_tie_round(r,'origin'); tie:=(v->>'round_id')::uuid;
 insert into qa_checks values('tie only tied candidates',v->>'candidate_count'='2' and v->>'male_slots'='1');
 insert into qa_checks values('tie exact unique electorate',(select count(*)=2 from public.voting_staff_pending(tie)));
 perform public.voting_enable_person(eid,p1,'QA-ROLLBACK-001',false);
 insert into qa_checks values('tie preserves original participant after revocation',(select count(*)=2 from public.voting_staff_pending(tie)));
 perform public.voting_admin_open_round(tie);
 perform set_config('request.jwt.claim.sub','',true);
 insert into qa_checks values('nonparticipant excluded',public.voting_enter('QA-ROLLBACK-003',9,-79)->>'reason'='not_in_tie_electorate');
 v:=public.voting_enter('QA-ROLLBACK-001',9,-79);
 insert into qa_checks values('origin voter can cast tie vote',public.voting_submit((v->>'token')::uuid,array[c1],9,-79)->>'state'='accepted');
 perform set_config('request.jwt.claim.sub',adm::text,true);
 perform public.voting_admin_close_active();
 insert into qa_checks values('origin history unchanged',(select sum(vote_count)=2 from public.voting_tallies where round_id=r));
 perform public.voting_enable_person(eid,p1,'QA-ROLLBACK-001',true);
 perform public.voting_admin_open_round(pr);
 perform set_config('request.jwt.claim.sub','',true);
 v:=public.voting_enter('QA-ROLLBACK-001',9,-79);
 insert into qa_checks values('practice independent of official',public.voting_submit((v->>'token')::uuid,array[pc],9,-79)->>'state'='accepted');
 if exists(select 1 from qa_checks where passed is distinct from true) then raise exception 'Remote QA assertion failed: %',(select string_agg(name,', ') from qa_checks where passed is distinct from true); end if;
end $$;
select count(*) checks,bool_and(passed) all_passed,jsonb_agg(name) verified from qa_checks;
rollback;
